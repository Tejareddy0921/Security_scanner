from datetime import datetime, timezone
from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field


class DetectionStatus(str, Enum):
    PENDING = "pending"
    PROCESSING = "processing"
    COMPLETED = "completed"
    FAILED = "failed"


class DetectionLabel(str, Enum):
    SCAM = "scam"
    NOT_SCAM = "not_scam"
    SUSPICIOUS = "suspicious"


class DetectionResult(BaseModel):
    """
    Stores the result generated by the scam detection system.
    """

    id: Optional[str] = Field(
        default=None,
        description="MongoDB document ID"
    )

    report_id: str = Field(
        ...,
        description="ID of the related scam report"
    )

    user_id: str = Field(
        ...,
        description="ID of the user who submitted the report"
    )

    status: DetectionStatus = Field(
        default=DetectionStatus.PENDING
    )

    label: Optional[DetectionLabel] = Field(
        default=None,
        description="Final AI classification"
    )

    confidence_score: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="AI confidence score between 0 and 1"
    )

    scam_type: Optional[str] = Field(
        default=None,
        description="Detected scam category"
    )

    explanation: Optional[str] = Field(
        default=None,
        description="Explanation for the AI classification"
    )

    risk_factors: list[str] = Field(
        default_factory=list,
        description="Indicators that contributed to the detection"
    )

    recommendations: list[str] = Field(
        default_factory=list,
        description="Safety recommendations for the user"
    )

    model_name: Optional[str] = Field(
        default=None,
        description="AI model used for detection"
    )

    processing_time_ms: Optional[float] = Field(
        default=None,
        ge=0
    )

    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    updated_at: Optional[datetime] = None