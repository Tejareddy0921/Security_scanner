from datetime import datetime, timezone
from typing import Optional

from pydantic import BaseModel, Field


class ScamReport(BaseModel):
    """
    Represents a scam report submitted by a user.
    """

    user_id: str = Field(
        ...,
        description="ID of the user who submitted the report"
    )

    content: str = Field(
        ...,
        min_length=1,
        description="Message, URL, email, or text reported by the user"
    )

    scam_type: Optional[str] = Field(
        default=None,
        description="Detected scam category"
    )

    is_scam: Optional[bool] = Field(
        default=None,
        description="Whether the submitted content is classified as a scam"
    )

    confidence_score: Optional[float] = Field(
        default=None,
        ge=0,
        le=1,
        description="AI confidence score between 0 and 1"
    )

    explanation: Optional[str] = Field(
        default=None,
        description="Explanation generated by the detection system"
    )

    status: str = Field(
        default="pending",
        description="Processing status of the report"
    )

    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )